import {createRequire} from 'node:module';
import {mkdirSync,writeFileSync} from 'node:fs';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url),{chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const here=dirname(fileURLToPath(import.meta.url)),out=resolve(process.argv[3]||resolve(here,'screenshots'));mkdirSync(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1200,height:1050},deviceScaleFactor:1});
const page=await context.newPage(),errors=[],requests=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>requests.push(r.url()));
const url=process.argv[2]||'http://127.0.0.1:5187/preview.html';
const wait=async()=>{await page.waitForFunction(()=>[...document.images].every(i=>i.complete&&i.naturalWidth>0))};
await page.goto(url);await wait();
assert.equal(await page.locator('#scene').evaluate(i=>i.naturalWidth),320);
assert.equal(await page.locator('#scene').getAttribute('width'),'640');
await page.screenshot({path:resolve(out,'desktop-normal.png')});
await page.locator('#scene-frame').screenshot({path:resolve(out,'scene-normal.png')});
await page.getByRole('button',{name:'深蓝屋顶'}).click();await wait();
assert.ok((await page.locator('#scene').getAttribute('src')).includes('deep-blue'));
await page.locator('#scene-frame').screenshot({path:resolve(out,'scene-deep-blue.png')});
await page.getByRole('button',{name:'×4',exact:true}).click();await wait();
assert.equal(await page.locator('#scene').getAttribute('width'),'1280');
await page.locator('#scene-frame').evaluate(e=>{e.scrollLeft=(e.scrollWidth-e.clientWidth)/2});
await page.locator('#scene-frame').screenshot({path:resolve(out,'scene-close.png')});
await page.locator('#grid').uncheck();await wait();assert.ok(!(await page.locator('#scene').getAttribute('src')).includes('-grid'));
await page.getByRole('button',{name:'×1',exact:true}).click();await wait();assert.equal(await page.locator('#scene').getAttribute('width'),'320');
await page.setViewportSize({width:390,height:844});await page.getByRole('button',{name:'×2',exact:true}).click();await wait();
await page.evaluate(()=>scrollTo(0,0));
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:resolve(out,'mobile-390.png')});
await page.setViewportSize({width:320,height:740});await wait();await page.evaluate(()=>scrollTo(0,0));assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:resolve(out,'mobile-320.png')});
assert.equal(errors.length,0);assert.ok(requests.every(u=>new URL(u).origin===new URL(url).origin));
assert.equal(await page.evaluate(()=>localStorage.length),0);assert.equal(await page.evaluate(()=>sessionStorage.length),0);
const result={url,browser:'Chrome headless isolated context',screenshots:['desktop-normal.png','scene-normal.png','scene-deep-blue.png','scene-close.png','mobile-390.png','mobile-320.png'],
  checks:{imagesLoaded:true,nativeImageDimensions:[320,256],sceneScales:[1,2,4],roofToggle:true,gridToggle:true,desktop:true,mobileWidths:[390,320],noPageHorizontalOverflow:true,noJavaScriptErrors:true,noExternalRequests:true,noStorageWrites:true},errors};
writeFileSync(resolve(out,'browser-verification.json'),JSON.stringify(result,null,2)+'\n',{flag:'wx'});
await browser.close();console.log(JSON.stringify(result,null,2));
